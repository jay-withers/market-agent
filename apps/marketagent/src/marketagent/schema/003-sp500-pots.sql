-- Two accounts replace the three sector pots (2026-11), to ask one question:
-- does the agent picking S&P 500 stocks beat simply holding the S&P 500?
--
-- * sp500: the agent, watching every S&P 500 constituent. Each run analyses at
--   most MAX_ANALYSES_PER_RUN of them (Terraform's local.pots sets 30), which is
--   what bounds the token cost of a 500-name watchlist.
-- * voo: passive. Holds Vanguard's S&P 500 ETF and reinvests idle cash
--   (jobs/passive.py), with no model. VOO rather than VUAA, the UCITS share
--   class: Alpaca trades US-listed instruments only. Same index, same provider;
--   VOO distributes where VUAA accumulates, and reinvesting the dividends makes
--   up the difference.
--
-- tech, health and energy are retired the way static-100 and dynamic-500 were:
-- inactive, history kept and readable, iterated by no job, route or tab.
--
-- The constituent list is a snapshot of Wikipedia's "List of S&P 500 companies"
-- taken 2026-11-06 (503 tickers; two share classes are dotted, as Alpaca
-- writes them). It is fixed, like every watchlist here: index changes are not
-- followed. Starting cash is a placeholder the first broker sync overwrites.

